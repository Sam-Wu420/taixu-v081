import './env';
import assert from 'node:assert/strict';
import {NodeField,NODE_CELL} from '../src/world/nodes';
import {SiteSys,SITE_CELL} from '../src/world/sites';
import {ACTIVE_MAP} from '../src/data/world';
import {guidanceExtras} from '../src/world/guidanceExtras';
import {guidanceCandidates,guidancePosition} from '../src/world/senseGuidance';
const ws:any={sites:{[`${ACTIVE_MAP}|1,0`]:{seen:1}}};
const event:any={id:1,x:1400,y:500,seen:true,done:false};
const hap:any={id:1,x:1500,y:500,seen:true,done:false};
const game:any={player:{x:0,y:0},awarenessRadius:6000,day:5,ws,events:{enc:[event]},happen:{haps:[hap]}};
game.nodes=new NodeField({} as any);
const node={key:'2:0',x:2.5*NODE_CELL,y:.5*NODE_CELL,kind:'herb',item:'hidden-detail',rare:false,seed:1} as const;
game.nodes.rememberVisible(node);
game.sites=new SiteSys(game);
const site={key:'1,0',x:1.5*SITE_CELL,y:.5*SITE_CELL,kind:'corpse'};
(game.sites as any).cache.set(site.key,site);
const extras=guidanceExtras(game);assert.equal(extras.length,4);
const c=guidanceCandidates([],[],0,0,100,6000,false,extras);assert.equal(c.length,4);
const refs=c.map(c=>c.ref);const pos=(ref:any)=>guidancePosition(ref,new Set(),new Set(),0,0,6000,false);
for(const ref of refs)assert.ok(pos(ref));
game.nodes.harvested.set(node.key,20);assert.equal(pos(refs.find(r=>r.type==='extra'&&r.actor.kind==='灵物气息')),null);
ws.sites[`${ACTIVE_MAP}|1,0`].seen=0;assert.equal(pos(refs.find(r=>r.type==='extra'&&r.actor.kind==='机缘气息')),null);
event.done=true; assert.equal(pos(refs.find(r=>r.type==='extra'&&r.actor.scope===event)),null);
game.happen.haps=[];assert.equal(pos(refs.find(r=>r.type==='extra'&&r.actor.scope===hap)),null);
const replacement={...event,done:false};game.events.enc=[replacement];assert.equal(pos(refs.find(r=>r.type==='extra'&&r.actor.scope===event)),null);
event.done=false;game.events.enc=[event];game.ws={sites:{}};assert.equal(pos(refs.find(r=>r.type==='extra'&&r.actor.scope===event)),null);
assert.equal(game.nodes.isKnownSignal(NaN,0,0),false);assert.equal(game.sites.isKnownSignal(NaN,0),false);
console.log('guidance extras: real observed node/site, event removal, depletion and save boundaries passed');
