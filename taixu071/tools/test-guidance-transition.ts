import './env';
import assert from 'node:assert/strict';
import {guidanceTransition} from '../src/world/guidanceTransition';
import {guidancePosition,type GuidanceActor} from '../src/world/senseGuidance';
const {NpcWorld}=await import('../src/world/npc');
const game:any={combat:{enemies:[]},player:{x:0,y:0}};
const world:any=Object.create(NpcWorld.prototype);world.game=game;
const person:any={id:'npc-a',alive:true,hidden:false,realm:1,stage:1,faction:'rogue',name:'某人',pers:'kind',met:true};
const npc:any={d:person,st:{x:1500,y:50},look:{},act:'idle'};
const active=new Map([[person.id,npc]]);
const before:GuidanceActor={type:'npc',actor:npc};
const enemy=world.toEnemy(npc,false);
const enemies=new Set<any>(game.combat.enemies);
let next=guidanceTransition(before,person,active,enemies,0,0,4000,false);
assert.equal(next?.type,'enemy');assert.equal(next?.actor,enemy);
assert.ok(next&&guidancePosition(next,enemies,new Set([npc]),0,0,4000,false));
enemy.hideT=1;assert.equal(guidanceTransition(before,person,active,enemies,0,0,4000,false),null);enemy.hideT=0;
enemy.affix={yinOn:true};assert.equal(guidanceTransition(before,person,active,enemies,0,0,4000,false),null);enemy.affix=undefined;
assert.equal(guidanceTransition(before,{...person},active,enemies,0,0,4000,false),null);
assert.equal(guidanceTransition(before,person,active,enemies,0,0,1000,false),null);
assert.equal(guidanceTransition(before,person,active,new Set(),0,0,4000,false),null);
const other:any={...enemy,npcId:'npc-b'};npc.enemy=other;assert.equal(guidanceTransition(before,person,active,new Set([other]),0,0,4000,false),null);
npc.enemy=undefined;const fromEnemy:GuidanceActor={type:'enemy',actor:enemy};
assert.equal(guidanceTransition(fromEnemy,person,active,new Set(),0,0,4000,false)?.actor,npc);
assert.equal(guidanceTransition(fromEnemy,person,active,enemies,0,0,4000,false),null);
person.hidden=true;assert.equal(guidanceTransition(fromEnemy,person,active,new Set(),0,0,4000,false),null);person.hidden=false;
enemy.dead=true;assert.equal(guidanceTransition(fromEnemy,person,active,new Set(),0,0,4000,false),null);enemy.dead=false;
const replacement={...npc,d:{...person}};assert.equal(guidanceTransition(fromEnemy,person,new Map([[person.id,replacement]]),new Set(),0,0,4000,false),null);
console.log('guidance transition: real NPC-to-enemy conversion and strict identity/perception boundaries passed');
// Combat.release is non-lethal but uses dead+sparing during removal. Nothing is rendered until the same NPC returns.
const {Combat}=await import('../src/world/combat');
const {guidancePendingReturn}=await import('../src/world/guidanceTransition');
const shell=world.toEnemy(npc,false,true);const shellRef:GuidanceActor={type:'enemy',actor:shell};
const combatMock:any={lock:shell};Combat.prototype.release.call(combatMock,shell);
assert.equal(shell.dead,true);assert.equal(shell.spar,true);assert.equal(combatMock.lock,null);
assert.equal(guidancePosition(shellRef,new Set([shell]),new Set([npc]),0,0,4000,false),null);
assert.equal(guidancePendingReturn(shellRef,person,active,0,0,4000,false),true);
assert.equal(guidanceTransition(shellRef,person,active,new Set([shell]),0,0,4000,false),null);
shell.hideT=1;assert.equal(guidancePendingReturn(shellRef,person,active,0,0,4000,false),false);shell.hideT=0;
person.hidden=true;assert.equal(guidancePendingReturn(shellRef,person,active,0,0,4000,false),false);person.hidden=false;
assert.equal(guidancePendingReturn(shellRef,person,active,0,0,1000,false),false);
assert.equal(guidancePendingReturn(shellRef,{...person},active,0,0,4000,false),false);
shell.spar=false;assert.equal(guidancePendingReturn(shellRef,person,active,0,0,4000,false),false);shell.spar=true;
npc.enemy=undefined;assert.equal(guidanceTransition(shellRef,person,active,new Set(),0,0,4000,false)?.actor,npc);
