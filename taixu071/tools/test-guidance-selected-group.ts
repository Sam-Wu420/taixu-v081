import assert from 'node:assert/strict';
import { readFileSync } from 'node:fs';
import { guidanceCandidates, guidancePosition, type GuidanceActor } from '../src/world/senseGuidance';
import { presentGuidance, guidanceText, guidanceRealmSummary } from '../src/world/guidancePresentation';
import { sameGuidanceActor, snapshotGuidanceExtras, validGuidanceTargets, guidanceExtraHeight } from '../src/world/guidanceTracking';
const scope={}, alive=[true,true,true];
const extras=[0,1,2].map(i=>({key:`site:${i}`,scope,point:{x:1200+i*100,y:0},kind:'机缘气息' as const,valid:()=>alive[i]}));
const enemies:any[]=[{x:1400,y:30,blv:2,def:{kind:'beast'}},{x:1500,y:35,blv:5,def:{kind:'beast'}},{x:1600,y:40,blv:0,def:{kind:'beast'}},{x:1450,y:30,blv:10,hideT:1,def:{kind:'beast'}}];
let c=guidanceCandidates(enemies,[],0,0,1000,3000,false,extras);
const groups=presentGuidance(c,0,0,new Map());
const monsters=groups.find(g=>g.kind==='妖物气息')!;
assert.equal(monsters.members.length,3, 'hidden beast never included');
assert.match(guidanceText(monsters,monsters.members.map(x=>x.distance)),/3道 · 2—5级及未知/);
assert.equal(guidanceRealmSummary(monsters.members.slice(0,1)),'2级');
assert.equal(guidanceRealmSummary([monsters.members[2]]),'未知');
const humans:any[]=[{x:1400,y:40,realm:1,def:{kind:'human'}},{x:1500,y:40,realm:3,def:{kind:'human'}}];
const people=guidanceCandidates(humans,[],0,0,1000,3000,false);assert.equal(guidanceRealmSummary(people),'炼气—结丹');
const points=groups.find(g=>g.kind==='机缘气息')!;
let playerX=0, radius=3000;
const pos=(r:GuidanceActor)=>guidancePosition(r,new Set(enemies),new Set(),playerX,0,radius,false);
const selected=snapshotGuidanceExtras(points.members,pos,1000);
assert.equal(selected.length,3);assert.ok(sameGuidanceActor(selected[0],{type:'extra',actor:{...extras[0]}}));
assert.equal(guidanceExtraHeight(selected[0]),180);
playerX=300;let v=validGuidanceTargets(selected,pos);assert.equal(v.length,3);
assert.ok(v[0].position.distance<=1000 && v[2].position.distance>1000, 'some selected enter inner while others remain outside');
alive[0]=false;v=validGuidanceTargets(selected,pos);assert.equal(v.length,2);assert.ok(!v.some(x=>sameGuidanceActor(x.ref,selected[0])));
radius=100;assert.equal(validGuidanceTargets(selected,pos).length,0,'lost sense drops tracking');
assert.equal(snapshotGuidanceExtras(monsters.members,pos,1000).length,0);
const ui=readFileSync('src/ui/SenseGuidance.tsx','utf8'),css=readFileSync('src/styles.css','utf8');
assert.match(ui,/snapshotGuidanceExtras\(source\.members/);assert.match(ui,/snapshotGuidanceActors\(source\.members/);
assert.match(ui,/sense-guidance-arrived/);assert.match(ui,/game\.life\.vis/);assert.match(ui,/removeFocus\(\)/);
assert.match(css,/\.sense-guidance-mark\.selected \{/);assert.match(css,/\.sense-guidance-arrived \{/);
console.log('selected guidance: rank summaries, hidden filtering, group snapshot, independent arrival, depletion and sense loss passed (UI wiring checked statically)');
