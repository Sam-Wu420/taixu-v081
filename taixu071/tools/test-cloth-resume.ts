import assert from 'node:assert/strict';
import { readFileSync } from 'node:fs';
import './env';
import { createCanvas } from '@napi-rs/canvas';
import { syncCharacterMotion } from '../src/core/characterMotion';
(globalThis as any).window = { innerWidth: 800, innerHeight: 600, devicePixelRatio: 1, addEventListener() {}, removeEventListener() {}, matchMedia: () => ({ matches: false }) };
(globalThis as any).localStorage = { getItem: () => null, setItem() {}, removeItem() {} };
const { CharState, HANLI_LOOK, drawCharacter, dressLook, DEFAULT_WARDROBE } = await import('../src/gfx/character');
const look = dressLook(HANLI_LOOK, { ...DEFAULT_WARDROBE.f, outfit: 'guangxiu' });
const st = new CharState(200, 300), ctx = createCanvas(900, 500).getContext('2d') as any;
const draw = (dt: number, ghost = false) => drawCharacter(ctx, look, st, 1.3, dt, { ghost });
st.update(1 / 60); draw(1 / 60);
const left: any = st.springs.get('hemL'); assert.ok(left);
st.setAction('sit');
for (let i = 0; i < 90; i++) { st.x += 2; st.update(1 / 60); draw(1 / 60); }
const oldSeen = left.lastSeen;
assert.ok(st.t - oldSeen > 0.25, 'sitting skips standing hem physics');
st.setAction('idle'); st.update(0.2);
const beforeGhost = { x: left.x, y: left.y, vx: left.vx, vy: left.vy, lastSeen: left.lastSeen };
draw(0, true);
assert.deepEqual({ x: left.x, y: left.y, vx: left.vx, vy: left.vy, lastSeen: left.lastSeen }, beforeGhost, 'ghost does not change real spring');
draw(1 / 60);
assert.equal(left.lastSeen, st.t); assert.equal(left.vx, 0); assert.equal(left.vy, 0);
assert.ok(Math.abs(left.x - beforeGhost.x) > 20, 'standing hem reattached to current position');
const motion = { vx: 4, vy: 5, speed: 6 };
syncCharacterMotion(motion, 10, 20, 13, 24, .5);
assert.deepEqual(motion, { vx: 6, vy: 8, speed: 10 });
syncCharacterMotion(motion, 13, 24, 13, 24, .5); assert.deepEqual(motion, { vx: 0, vy: 0, speed: 0 });
syncCharacterMotion(motion, 0, 0, 10, 10, 0); assert.deepEqual(motion, { vx: 0, vy: 0, speed: 0 });
const cave = readFileSync('src/ui/CaveScene.tsx', 'utf8');
assert.match(cave, /equipmentAppearance\(game\.player\.look, game\.hero\.equip, game\.hero\.wardrobe\?\.showEquipment === true\)/);
assert.equal((cave.match(/syncCharacterMotion\(/g) || []).length, 2, 'both cave characters update their actual motion');
console.log('cloth resume: sitting/standing reattachment, ghost isolation, cave motion and equipped appearance integration passed');
