// 太虚问道录 · NPC 自由对话（前端部分）验收：人物卡、玩家卡、称呼分寸、记忆、好感结算、讲价、动手
// 用法：npx tsx tools/test-chat.ts（不连模型：把后端换成假的）
import './env';
(globalThis as any).window = { innerWidth: 1280, innerHeight: 800, devicePixelRatio: 1, addEventListener() {}, removeEventListener() {}, matchMedia: () => ({ matches: false }) };
const mem = new Map<string, string>(); (globalThis as any).localStorage = { getItem: (k: string) => mem.get(k) ?? null, setItem: (k: string, v: string) => { mem.set(k, v); }, removeItem: (k: string) => { mem.delete(k); } };
(globalThis as any).__FANREN_NORELOAD = true;
const { Terrain } = await import('../src/world/terrain');
const { Game } = await import('../src/world/game');
let fails = 0, n = 0;
const ok = (c: any, msg: string) => { n++; if (!c) { fails++; console.log('  ✗', msg); } else console.log('  ✓', msg); };
let reply: any = { ok: true, say: '道友请了。', act: '拱手', tone: 'polite', delta: 1, bargain: 'none', price: 1, note: '' };
let sent: any = null;
(globalThis as any).fetch = async (_u: string, o: any) => { sent = JSON.parse(o.body); return { ok: true, json: async () => reply }; };
const t = new Terrain(); t.build(); const g = new Game(t); g.reset();
const d = g.npcs.list.find((x) => x.alive && x.realm === 1 && !x.canon && !x.beauty && x.pers === 'arrogant')!;
d.favor = 0;
g.hero.realm = 1; g.hero.stage = 2;
await g.chat.send({ kind: 'npc', id: d.id }, '道友好');
ok(sent?.npc?.name === d.name && sent.npc.pers && sent.npc.voice && sent.npc.realm, '人物卡：名字、性情、口吻、修为');
ok(sent.player.realm && sent.player.sect && sent.player.purse && sent.world.date && sent.world.hour, '玩家卡与世界：境界、宗门、身家、日期时辰');
ok(sent.player.name.includes('尚未通名'), '初次见面：对方不知道你的名字');
ok(/道友/.test(sent.etiquette), `同境界：以道友相称（${sent.etiquette.slice(0, 20)}…）`);
g.hero.realm = 4; await g.chat.send({ kind: 'npc', id: d.id }, '……');
ok(/前辈/.test(sent.etiquette) && /晚辈/.test(sent.etiquette), '玩家高两个大境界：对方称前辈、自称晚辈');
ok(sent.player.name === '苏寒' && sent.history.length === 2, '聊过之后：认得你、带上前面的对话');
reply = { ...reply, delta: 8, note: '此人自称苏寒' }; const f0 = d.favor;
for (let i = 0; i < 4; i++) await g.chat.send({ kind: 'npc', id: d.id }, '久仰');
ok(d.favor - f0 <= 12, `好感每日正向至多 +12（实际 +${d.favor - f0}）`);
ok((g.ws as any).chat['npc:' + d.id].notes.includes('此人自称苏寒'), '记下对方说的事');
reply = { ...reply, tone: 'insult', delta: -30, note: '' };
for (let i = 0; i < 4; i++) await g.chat.send({ kind: 'npc', id: d.id }, '滚');
ok(d.favor <= -50 && d.grudge === 1, `被骂狠了：好感 ${Math.round(d.favor)}，结下梁子`);
const shop = { title: '嘉禾城 · 丹药铺', stock: [{ id: 'pill_juqi', price: 100, n: 5 }], sellRate: 0.5, loc: 'jiayuan' } as any;
reply = { ok: true, say: '给您九折。', tone: 'kind', delta: 2, bargain: 'great', price: 0.9 };
await g.chat.send({ kind: 'keeper', shop }, '便宜点');
ok(shop.stock[0].price === 90 && sent.npc.identity.includes('掌柜'), '掌柜讲价：货价打九折');
reply = { ok: false, fallback: true };
const r = await g.chat.send({ kind: 'npc', id: d.id }, '在吗');
ok(r.fallback && typeof r.say === 'string' && r.say.length > 0, '后端出错：用本地台词兜底，不打断游戏');
console.log(fails ? `${n - fails}/${n} 通过，${fails} 项失败` : `${n}/${n} 通过`);
process.exit(fails ? 1 : 0);
