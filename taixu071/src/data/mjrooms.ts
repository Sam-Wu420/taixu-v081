// v0.54：秘境石室模板——先设计好一批形状各异的石室，进秘境时随机挑选、旋转、镜像，再拼成一张图（world/mijing.ts）。
// 每次进去拼法都不一样，每一间又都是有设计的。
//
// 字符：
//   #  岩体（石室外的山腹；石室里的 # 就是石柱 / 石墩）
//   .  地面
//   W  水池 / 熔岩 / 深渊 / 冰湖（按主题画，走不过去）
//   +  门（只能在边上；拼接时由甬道接上，三格宽）
//   E  妖物出没点      B  首领站位      C  宝匣          H  灵草
//   S  古碑            X  古阵（出口 / 去下一层）
//   P  大摆件（柱、像、祭坛）  L  灯火（发光）  d  小摆件（白骨、碎石、灵晶）
// 用途：entry 入口 · hall 石室 · treasure 宝库 · herb 药圃 · shrine 碑室 · boss 首领 · link 过道（无妖物）

